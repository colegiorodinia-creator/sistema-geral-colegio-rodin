export const LE_PERINI_COC_SET = new Set(LE_PERINI_COC_LIST);

/**
 * Verifica se um estudante ou matrícula é do convênio Le Perini (DLP).
 * @param {object} student
 * @param {object} enrollment
 * @returns {boolean}
 */
export function checkIsLePerini(student, enrollment) {
  // Se explicitamente marcado como booleano no objeto ativo (ex: formulário ou edição do usuário)
  if (student && typeof student.isLePerini === 'boolean' && student.isLePeriniManual) {
    return student.isLePerini;
  }
  if (enrollment && typeof enrollment.isLePerini === 'boolean' && enrollment.isLePeriniManual) {
    return enrollment.isLePerini;
  }

  // Checagem por COC / RM / ID
  const candidates = [
    student?.cocCode,
    student?.rmNumber,
    student?.id,
    enrollment?.cocCode,
    enrollment?.rmNumber,
    enrollment?.studentId,
    enrollment?.id
  ].filter(Boolean);

  for (const c of candidates) {
    const clean = String(c).replace(/^\D+/, '').replace(/^0+/, '');
    if (clean && LE_PERINI_COC_SET.has(clean)) {
      return true;
    }
  }

  // Checagem por texto de desconto / tipo
  const texts = [
    student?.tipo_desconto_2027,
    student?.observacao_desconto_2027,
    student?.desconto_2026_detalhes,
    student?.discountDescription,
    enrollment?.tuitionDiscountType,
    enrollment?.tuitionDiscountReason,
    enrollment?.discountDescription,
    enrollment?.notes,
    enrollment?.observations
  ].filter(Boolean).join(' ').toUpperCase();

  if (texts.includes('DLP') || texts.includes('LE PERINI') || texts.includes('LEPERINI')) {
    return true;
  }

  return false;
}
